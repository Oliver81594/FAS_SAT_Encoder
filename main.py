import subprocess
from argparse import ArgumentParser

def load_instance(input_file_name):
    k, n, m, edges = 0, 0, 0, []
    with open(input_file_name, "r") as file:
        lines = file.readlines()
        k = int(lines[0].strip())
        n, m = map(int, lines[1].strip().split())
        for i in range(m):
            i, j = map(int, lines[2+i].strip().split())
            edges.append((i,j))

    return (k, n, m, edges)


